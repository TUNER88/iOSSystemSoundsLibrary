#!/usr/bin/env python3
"""Generate Sources/SystemSoundsLibrary/SystemSound+Catalog.swift from data/sounds.json.

Usage:
  python3 scripts/generate_swift.py          # write the file
  python3 scripts/generate_swift.py --check  # exit 1 if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Sources/SystemSoundsLibrary/SystemSound+Catalog.swift"
KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init",
    "inout", "internal", "let", "open", "operator", "private", "protocol", "public", "rethrows", "static",
    "struct", "subscript", "typealias", "var", "break", "case", "continue", "default", "defer", "do",
    "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return", "switch", "where", "while",
    "as", "any", "catch", "false", "is", "nil", "super", "self", "Self", "throw", "throws", "true", "try",
}
RESERVED = {"all", "directory", "custom", "sound"}
STATUS = {"current": ".current", "changed-since-ios7": ".changedSinceIOS7", "removed": ".removed"}


def lit(v):
    return "nil" if v is None else json.dumps(v, ensure_ascii=False)


def ident(name):
    assert name not in RESERVED, name
    return f"`{name}`" if name in KEYWORDS else name


def build():
    sounds = json.loads((ROOT / "data/sounds.json").read_text())["sounds"]
    lines = [
        "// Generated by scripts/generate_swift.py from data/sounds.json. Do not edit by hand.",
        "// SystemSoundID mappings and minimum iOS versions are derived from",
        "// https://github.com/p-x9/swift-system-sound (MIT, Copyright (c) 2023 p-x9); see NOTICE.",
        "",
        "import AudioToolbox",
        "",
        "extension SystemSound {",
        f"    /// All {len(sounds)} known system sounds, sorted by ID.",
        "    public static let all: [SystemSound] = [",
    ]
    for s in sounds:
        lines.append(
            f"        SystemSound(id: {s['id']}, name: {lit(s['name'])}, fileName: {lit(s['file'])}, folder: {lit(s['folder'])}, "
            f"category: {lit(s['category'])}, minimumIOSVersion: {lit(s['minIOS'])}, status: {STATUS[s['status']]}, confidence: .{s['confidence']}),"
        )
    lines += ["    ]", ""]
    for i, s in enumerate(sounds):
        doc = f"    /// `{s['id']}`"
        if s["file"]:
            doc += f" · `{s['path']}`"
        if s["category"]:
            doc += f" · {s['category']}"
        lines.append(doc)
        lines.append(f"    ///")
        lines.append(f"    /// Confidence: {s['confidence']}." + (f" Available since iOS {s['minIOS']}." if s["minIOS"] else ""))
        if s["notes"]:
            lines.append(f"    /// - Note: {s['notes']}")
        if s["status"] == "removed":
            lines.append(f"    @available(*, deprecated, message: {json.dumps('The sound file no longer exists on recent iOS versions. ' + (s['notes'] or ''))})")
        if s["minIOS"] and float(s["minIOS"]) > 15.0:
            lines.append(f"    @available(iOS {s['minIOS']}, *)")
        lines.append(f"    public static var {ident(s['name'])}: SystemSound {{ all[{i}] }}")
        lines.append("")
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def main():
    content = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != content:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 scripts/generate_swift.py")
            sys.exit(1)
        print("Swift catalog is up to date")
        return
    OUT.write_text(content)


if __name__ == "__main__":
    main()
